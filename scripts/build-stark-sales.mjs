// Builds lib/data/starkSales.js — Stark County, OH (Canton / Massillon /
// Alliance) median sale prices from the County Auditor's own GIS
// (scgisa.starkcountyohio.gov). Run monthly:
//
//   NODE_USE_ENV_PROXY=1 node scripts/build-stark-sales.mjs
//
// Rules (all from the Auditor's data, nothing estimated):
//  - StarkCountySales: SALE_VALIDITY "0-QUALIFIED - ARMSLENGTH" only (the
//    Auditor's own codes: 1-QUALIFIED - QUESTIONABLE, E- relatives, G- estate,
//    H- forced sale, D- bank, M- private FSBO … all excluded), NUMBER_OF_PARCELS
//    = 1, SALE_TYPE not "1+LAND" (sold as land), price $10,000+
//  - the layer repeats a sale on several rows → one sale per parcel + date + price
//  - home type + ZIP from StarkCountyParcels (LAND_USE_DESCRIPTION,
//    SITE_ADDRESS3): 1-family dwellings, condominium units, 2-family dwellings
//  - 12 months up to the latest qualified sale; per ZIP + type; 10+ sales
// Never requested: FORMER_OWNER / NEW_OWNER (names).
import { writeFileSync } from "node:fs";

const B = "https://scgisa.starkcountyohio.gov/arcgis/rest/services/Auditor/";
const SALES = B + "StarkCountySales/MapServer/0/query";
const PARCELS = B + "StarkCountyParcels/FeatureServer/0/query";
const MIN = 10;
const TYPES = { "R - 1-FAMILY DWELLING": "1F", "C - CONDOMINIUM RESIDENTIAL UNIT": "CN", "R - 2-FAMILY DWELLING": "2F" };
const LABELS = { "1F": "single-family homes", CN: "condominium units", "2F": "two-family homes" };

async function q(url, params) {
  const body = new URLSearchParams({ returnGeometry: "false", f: "json", ...params });
  for (let i = 0; i < 6; i++) {
    try {
      const r = await fetch(url, { method: "POST", body, headers: { "content-type": "application/x-www-form-urlencoded" }, signal: AbortSignal.timeout(120000) });
      const j = await r.json();
      if (j.error) throw new Error(JSON.stringify(j.error));
      return j;
    } catch (e) { if (i === 5) throw e; await new Promise((r) => setTimeout(r, 5000 * (i + 1))); }
  }
}

const since = new Date(Date.now() - 400 * 864e5).toISOString().slice(0, 10);
const raw = [];
for (let off = 0; ; ) {
  const j = await q(SALES, { where: `SALE_VALIDITY LIKE '0-QUALIFIED%' AND NUMBER_OF_PARCELS=1 AND TRANSFER_DATE >= DATE '${since}'`, outFields: "OBJECTID,PARID,TRANSFER_DATE,SALE_PRICE,SALE_TYPE", orderByFields: "OBJECTID", resultOffset: String(off), resultRecordCount: "2000" });
  raw.push(...j.features.map((f) => f.attributes));
  off += j.features.length;
  if (j.features.length < 2000 && !j.exceededTransferLimit) break;
}
const seen = new Set(), sales = [];
for (const r of raw) {
  const k = `${r.PARID}|${r.TRANSFER_DATE}|${r.SALE_PRICE}`;
  if (seen.has(k)) continue;
  seen.add(k);
  if (r.SALE_TYPE !== "1+LAND" && Number(r.SALE_PRICE) >= 10000) sales.push(r);
}
const last = Math.max(...sales.map((r) => r.TRANSFER_DATE));
const window = sales.filter((r) => r.TRANSFER_DATE >= last - 365 * 864e5);
console.log(raw.length, "rows →", window.length, "qualified sales in the 12-month window");

const pins = [...new Set(window.map((r) => String(r.PARID)))];
const par = new Map();
for (let i = 0; i < pins.length; i += 200) {
  const ids = pins.slice(i, i + 200).map((p) => `'${p}'`).join(",");
  const j = await q(PARCELS, { where: `PIN IN (${ids})`, outFields: "PIN,LAND_USE_DESCRIPTION,SITE_ADDRESS3" });
  for (const f of j.features) par.set(String(f.attributes.PIN), f.attributes);
  await new Promise((r) => setTimeout(r, 500));
}
const groups = new Map();
for (const r of window) {
  const p = par.get(String(r.PARID));
  const t = p && TYPES[p.LAND_USE_DESCRIPTION];
  const zip = p && String(p.SITE_ADDRESS3 || "").match(/(\d{5})/)?.[1];
  if (!t || !zip) continue;
  const k = `${zip}|${t}`;
  if (!groups.has(k)) groups.set(k, []);
  groups.get(k).push(r);
}
const med = (a) => { const s = a.slice().sort((x, y) => x - y), n = s.length; return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2; };
const day = (t) => new Date(t).toISOString().slice(0, 10);
const out = {};
for (const [k, rs] of groups) {
  if (rs.length < MIN) continue;
  const d = rs.map((r) => r.TRANSFER_DATE).sort((a, b) => a - b);
  out[k] = { n: rs.length, median: med(rs.map((r) => Number(r.SALE_PRICE))), from: day(d[0]), to: day(d[d.length - 1]) };
}
const meta = { built: new Date().toISOString().slice(0, 10), windowFrom: day(last - 365 * 864e5), windowTo: day(last), sales: window.length, groups: Object.keys(out).length, types: LABELS };
writeFileSync(new URL("../lib/data/starkSales.js", import.meta.url),
  `// Generated by scripts/build-stark-sales.mjs — do not edit by hand.\n// Stark County Auditor: "0-QUALIFIED - ARMSLENGTH" single-parcel sales, 12 months,\n// median price per ZIP + home type (1F / CN / 2F), 10+ sales.\nexport const STARK_SALES_META = ${JSON.stringify(meta)};\nexport const STARK_SALES = ${JSON.stringify(out)};\n`);
console.log(meta);
