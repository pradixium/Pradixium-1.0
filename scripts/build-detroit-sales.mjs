// Builds lib/data/detroitSales.js from the City of Detroit Office of the
// Assessor's "Property Sales" (data.detroitmi.gov, updated daily). The
// live service is fast on sale_date but takes 30 s+ on a neighborhood
// filter, so the neighborhood medians are prebuilt here. Run monthly:
//
//   NODE_USE_ENV_PROXY=1 node scripts/build-detroit-sales.mjs
//
// Rules (all from the file itself, nothing estimated):
//  - only the assessor's Michigan terms-of-sale code "03-ARM'S LENGTH",
//    100% of a single parcel (not a multi-parcel sale), price > 0
//  - sale dates in the 12 months up to the latest sale in the file; any
//    date after the build date is dropped as a data-entry error
//  - grouped by the assessor's ECF neighborhood + property class code
//    (condos have their own "C…" ECF neighborhoods)
//  - a group is published only with 10+ sales
// Never requested: grantor / grantee (names).
import { writeFileSync } from "node:fs";

const SALES_URL = "https://services2.arcgis.com/qvkbeam7Wirps6zC/arcgis/rest/services/assessor_property_sales_view/FeatureServer/0/query";
const FIELDS = "sale_id,sale_date,amt_sale_price,term_of_sale,pct_property_transferred,is_multi_parcel_sale,property_class_code,property_class_description,ecf_neighborhood";
const MIN_SALES = 10;
const today = new Date().toISOString().slice(0, 10);
const since = new Date(Date.now() - 400 * 86400000).toISOString().slice(0, 10); // a margin; trimmed below

async function page(offset) {
  const body = new URLSearchParams({ where: `sale_date >= '${since}' AND term_of_sale='03-ARM''S LENGTH'`, outFields: FIELDS, orderByFields: "sale_id", resultOffset: String(offset), resultRecordCount: "1000", returnGeometry: "false", f: "json" });
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const r = await fetch(SALES_URL, { method: "POST", body, headers: { "content-type": "application/x-www-form-urlencoded" }, signal: AbortSignal.timeout(90000) });
      const j = await r.json();
      if (Array.isArray(j.features)) return j;
    } catch {}
    await new Promise((res) => setTimeout(res, 3000 * (attempt + 1)));
  }
  throw new Error("page failed at offset " + offset);
}

const rows = [];
for (let offset = 0; ; offset += 1000) {
  const j = await page(offset);
  rows.push(...j.features.map((f) => f.attributes));
  process.stderr.write(`\r${rows.length} rows`);
  if (!j.exceededTransferLimit && j.features.length < 1000) break;
}
process.stderr.write("\n");

const seen = new Set();
const ok = rows.filter((r) => {
  if (seen.has(r.sale_id)) return false;
  seen.add(r.sale_id);
  const d = String(r.sale_date || "").slice(0, 10);
  return r.term_of_sale === "03-ARM'S LENGTH" && Number(r.pct_property_transferred) === 100 && String(r.is_multi_parcel_sale) === "False" && Number(r.amt_sale_price) > 0 && d && d <= today && r.ecf_neighborhood && r.property_class_code;
});
const latest = ok.map((r) => String(r.sale_date).slice(0, 10)).sort().pop();
const from = new Date(Date.parse(latest) - 365 * 86400000).toISOString().slice(0, 10);
const groups = {};
for (const r of ok) {
  const d = String(r.sale_date).slice(0, 10);
  if (d <= from) continue;
  const k = `${String(r.ecf_neighborhood).trim().toUpperCase()}|${r.property_class_code}`;
  (groups[k] ||= { label: r.property_class_description, prices: [], dates: [] });
  groups[k].prices.push(Number(r.amt_sale_price));
  groups[k].dates.push(d);
}
const out = {};
for (const [k, g] of Object.entries(groups)) {
  if (g.prices.length < MIN_SALES) continue;
  const p = g.prices.sort((a, b) => a - b), m = Math.floor(p.length / 2);
  const d = g.dates.sort();
  out[k] = { n: p.length, median: Math.round(p.length % 2 ? p[m] : (p[m - 1] + p[m]) / 2), from: d[0], to: d[d.length - 1], label: g.label };
}
const meta = { built: today, windowFrom: from, windowTo: latest, sales: ok.filter((r) => String(r.sale_date).slice(0, 10) > from).length, groups: Object.keys(out).length };
writeFileSync(new URL("../lib/data/detroitSales.js", import.meta.url),
  `// Generated by scripts/build-detroit-sales.mjs — do not edit by hand.\n// City of Detroit Office of the Assessor, Property Sales: arm's-length (03) single-parcel sales,\n// median price per ECF neighborhood | property class code, 12 months, 10+ sales.\nexport const DETROIT_SALES_META = ${JSON.stringify(meta)};\nexport const DETROIT_SALES = ${JSON.stringify(out)};\n`);
console.log(meta);
