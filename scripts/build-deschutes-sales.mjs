// Builds lib/data/deschutesSales.js — Deschutes County, OR (Bend / Redmond /
// Sisters / La Pine) median sale prices from the County Assessor's own open
// data tables (maps.deschutes.org OpenData/TablesFD). Run monthly:
//
//   NODE_USE_ENV_PROXY=1 node scripts/build-deschutes-sales.mjs
//
// Rules (all from the Assessor's data, nothing estimated):
//  - Sales (table 9): latest sale with reject code 33 "CONFIRMED SALE", price
//    $10,000+; a Book_Page on several taxlots = multi-parcel deed → dropped
//  - 12 months up to the latest confirmed sale in the table
//  - ZIP from Assessor Account (table 1); type from Property Class/Stat Class
//    (table 6): every class row of the taxlot is Oregon property class 101
//    (residential improved) and exactly ONE row is a dwelling — the county's
//    own STAT_CLASS_DESC "One story… / Two story… / Split level…" → house,
//    "Townhouse" → townhouse
//  - per ZIP + type, 10+ sales
// Never requested: Seller_1/2, Buyer_1/2, Owners, Mailing Addresses.
import { writeFileSync } from "node:fs";

const D = "https://maps.deschutes.org/arcgis/rest/services/OpenData/TablesFD/MapServer/";
const MIN = 10;
const HOUSE = /^(one story|two story|split level|tri-level|one and one-half story|multi-story)/i;

// old MapServer: no resultRecordCount / orderBy → page by OBJECTID; GET only
async function q(table, where, fields) {
  const out = [];
  for (let last = 0; ; ) {
    const p = new URLSearchParams({ where: `(${where}) AND OBJECTID > ${last}`, outFields: `OBJECTID,${fields}`, returnGeometry: "false", f: "json" });
    let j;
    for (let i = 0; i < 5; i++) {
      try {
        const r = await fetch(`${D}${table}/query?${p}`, { headers: { "user-agent": "curl/8.5.0" }, signal: AbortSignal.timeout(120000) });
        j = await r.json();
        if (j.error) throw new Error(JSON.stringify(j.error));
        break;
      } catch (e) { if (i === 4) throw e; await new Promise((r) => setTimeout(r, 4000 * (i + 1))); }
    }
    const f = j.features || [];
    out.push(...f.map((x) => x.attributes));
    if (f.length < 1000) break;
    last = Math.max(...f.map((x) => x.attributes.OBJECTID));
  }
  return out;
}

const since = new Date(Date.now() - 460 * 864e5).toISOString().slice(0, 10);
const raw = await q(9, `Reject_Code_1='33' AND Sales_Date_1 >= DATE '${since}'`, "Taxlot,Book_Page_1,Total_Sales_Price_1,Sales_Date_1");
const last = Math.max(...raw.map((s) => s.Sales_Date_1));
const win = raw.filter((s) => s.Sales_Date_1 >= last - 365 * 864e5);
const bp = new Map();
for (const s of win) bp.set(s.Book_Page_1, (bp.get(s.Book_Page_1) || 0) + 1);
const sales = win.filter((s) => s.Book_Page_1 && bp.get(s.Book_Page_1) === 1 && Number(s.Total_Sales_Price_1) >= 10000);
console.log(raw.length, "confirmed sales →", sales.length, "single-taxlot sales in the 12-month window");

const lots = [...new Set(sales.map((s) => s.Taxlot))];
const acc = new Map(), cls = new Map();
for (let i = 0; i < lots.length; i += 80) {
  const ids = lots.slice(i, i + 80).map((l) => `'${l}'`).join(",");
  for (const a of await q(1, `TaxLot IN (${ids})`, "TaxLot,Zip")) { if (!acc.has(a.TaxLot)) acc.set(a.TaxLot, []); acc.get(a.TaxLot).push(a); }
  for (const c of await q(6, `TAXLOT IN (${ids})`, "TAXLOT,PROPERTY_CLASS,STAT_CLASS_DESC")) { if (!cls.has(c.TAXLOT)) cls.set(c.TAXLOT, []); cls.get(c.TAXLOT).push(c); }
}
function kindOf(rows) {
  if (!rows?.length || rows.some((c) => String(c.PROPERTY_CLASS) !== "101")) return null;
  const dw = rows.filter((c) => HOUSE.test(c.STAT_CLASS_DESC || "") || /^townhouse$/i.test(c.STAT_CLASS_DESC || ""));
  if (dw.length !== 1) return null;
  return /^townhouse$/i.test(dw[0].STAT_CLASS_DESC) ? "TH" : "H";
}
const groups = new Map();
for (const s of sales) {
  const a = acc.get(s.Taxlot), k = kindOf(cls.get(s.Taxlot));
  const zips = [...new Set((a || []).map((x) => String(x.Zip || "").slice(0, 5)).filter((z) => /^\d{5}$/.test(z)))];
  if (!k || zips.length !== 1) continue;
  const key = `${zips[0]}|${k}`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(s);
}
const med = (a) => { const s = a.slice().sort((x, y) => x - y), n = s.length; return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2; };
const day = (t) => new Date(t).toISOString().slice(0, 10);
const out = {};
for (const [k, rs] of groups) {
  if (rs.length < MIN) continue;
  const d = rs.map((r) => r.Sales_Date_1).sort((a, b) => a - b);
  out[k] = { n: rs.length, median: med(rs.map((r) => Number(r.Total_Sales_Price_1))), from: day(d[0]), to: day(d[d.length - 1]) };
}
const meta = { built: new Date().toISOString().slice(0, 10), windowFrom: day(last - 365 * 864e5), windowTo: day(last), sales: sales.length, groups: Object.keys(out).length, types: { H: "single-family houses", TH: "townhouses" } };
writeFileSync(new URL("../lib/data/deschutesSales.js", import.meta.url),
  `// Generated by scripts/build-deschutes-sales.mjs — do not edit by hand.\n// Deschutes County Assessor: reject code 33 "CONFIRMED SALE" single-taxlot sales, 12 months,\n// median price per ZIP + type (H house / TH townhouse, property class 101), 10+ sales.\nexport const DESCHUTES_SALES_META = ${JSON.stringify(meta)};\nexport const DESCHUTES_SALES = ${JSON.stringify(out)};\n`);
console.log(meta, out);
