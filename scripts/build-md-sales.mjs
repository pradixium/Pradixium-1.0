// Builds lib/data/mdSales.js — Maryland (Baltimore + the DC suburbs +
// every county): median price of private ARM'S-LENGTH transfers of
// improved property (SDAT "How Conveyed" CONVEY1 = 1) per ZIP code and
// residence type (RESITYP: SF single-family, TH townhouse, CN condominium),
// 12 months up to the latest transfer in the file. Run after each monthly
// SDAT refresh of the Maryland Department of Planning MD_PropertyData
// service (the live service takes ~13 s for one ZIP query, too slow for a
// report):
//
//   NODE_USE_ENV_PROXY=1 node scripts/build-md-sales.mjs
//
// Rules (from the file itself, nothing estimated): CONVEY1 = 1 only
// (2 = vacant, 3 = multiple parcels, 4 = non-arm's-length), price > $1,000,
// a date after the build date is dropped, 10+ sales per group. Each SDAT
// account carries its LATEST transfer, so a home resold twice in the year
// counts once. Owner fields are never requested.
import { writeFileSync } from "node:fs";

const SVC = "https://mdgeodata.md.gov/imap/rest/services/PlanningCadastre/MD_PropertyData/MapServer/0/query";
const TYPES = { SF: "single-family homes", TH: "townhouses", CN: "condominiums" };
const MIN_SALES = 10;
const today = new Date().toISOString().slice(0, 10).replace(/-/g, "");

async function get(params) {
  for (let i = 0; i < 4; i++) {
    try {
      const r = await fetch(SVC, { method: "POST", body: new URLSearchParams({ returnGeometry: "false", f: "json", ...params }), signal: AbortSignal.timeout(120000) });
      const j = await r.json();
      if (Array.isArray(j.features)) return j;
    } catch {}
    await new Promise((res) => setTimeout(res, 4000 * (i + 1)));
  }
  throw new Error("query failed " + JSON.stringify(params).slice(0, 120));
}

const latest = (await get({ where: "CONVEY1=1", outStatistics: JSON.stringify([{ statisticType: "max", onStatisticField: "TRADATE", outStatisticFieldName: "mx" }]) })).features[0].attributes.mx;
const d = new Date(Date.UTC(+latest.slice(0, 4), +latest.slice(4, 6) - 1, +latest.slice(6, 8)) - 365 * 86400000);
const from = d.toISOString().slice(0, 10).replace(/-/g, "");
const rows = [];
for (let offset = 0; ; offset += 2000) {
  const j = await get({ where: `CONVEY1=1 AND TRADATE>'${from}' AND TRADATE<='${latest}' AND RESITYP IN ('SF','TH','CN')`, outFields: "OBJECTID,ZIPCODE,RESITYP,TRADATE,CONSIDR1", orderByFields: "OBJECTID", resultOffset: String(offset), resultRecordCount: "2000" });
  rows.push(...j.features.map((f) => f.attributes));
  process.stderr.write(`\r${rows.length}`);
  if (j.features.length < 2000 && !j.exceededTransferLimit) break;
}
process.stderr.write("\n");
const groups = {};
const seen = new Set();
for (const r of rows) {
  if (seen.has(r.OBJECTID)) continue; seen.add(r.OBJECTID);
  const zip = String(r.ZIPCODE || "").slice(0, 5), price = Number(r.CONSIDR1), t = String(r.TRADATE || "");
  if (!/^\d{5}$/.test(zip) || !(price > 1000) || !TYPES[r.RESITYP] || t > today) continue;
  const k = `${zip}|${r.RESITYP}`;
  (groups[k] ||= { p: [], d: [] });
  groups[k].p.push(price); groups[k].d.push(t);
}
const iso = (t) => `${t.slice(0, 4)}-${t.slice(4, 6)}-${t.slice(6, 8)}`;
const out = {};
for (const [k, g] of Object.entries(groups)) {
  if (g.p.length < MIN_SALES) continue;
  const p = g.p.sort((a, b) => a - b), m = Math.floor(p.length / 2), ds = g.d.sort();
  out[k] = { n: p.length, median: Math.round(p.length % 2 ? p[m] : (p[m - 1] + p[m]) / 2), from: iso(ds[0]), to: iso(ds[ds.length - 1]) };
}
const meta = { built: iso(today), windowFrom: iso(from), windowTo: iso(latest), sales: seen.size, groups: Object.keys(out).length };
writeFileSync(new globalThis.URL("../lib/data/mdSales.js", import.meta.url),
  `// Generated by scripts/build-md-sales.mjs — do not edit by hand.\n// Maryland SDAT (MD_PropertyData): CONVEY1 = 1 arm's-length transfers, median price per "ZIP|RESITYP", 12 months, 10+ sales.\nexport const MD_SALES_META = ${JSON.stringify(meta)};\nexport const MD_SALES_TYPES = ${JSON.stringify(TYPES)};\nexport const MD_SALES = ${JSON.stringify(out)};\n`);
console.log(meta);
